-- CashmereTrace MN - Phase 1 schema
-- Source of truth: CashmereTrace_MN_Final_Plan.md section 5,
-- reconciled with docs/BACKEND_ARCHITECTURE_PLAN.md sections 3 and 4.6.
--
-- Naming reconciliation:
--   quality_test, system_config, aimags, sums, batch_counter(sequence) follow
--   the final project plan. The PDF data dictionary requires a separate
--   suppliers table; it is included and linked from profiles.supplier_id.
--   Quality columns keep the approved units from the data dictionary.
--
-- No seed data is inserted here. No authoritative aimag/sum list exists in
-- the repository; cashmeretrace/lib/mock/geo.ts is explicitly mock data.

create table public.aimags (
  id bigint generated by default as identity primary key,
  code varchar(10) not null,
  name varchar(100) not null,
  created_at timestamptz not null default now(),
  constraint aimags_code_unique unique (code),
  constraint aimags_name_unique unique (name)
);

create table public.sums (
  id bigint generated by default as identity primary key,
  aimag_id bigint not null,
  code varchar(10) not null,
  name varchar(100) not null,
  created_at timestamptz not null default now(),
  constraint sums_aimag_fkey foreign key (aimag_id)
    references public.aimags (id) on update restrict on delete restrict,
  constraint sums_aimag_code_unique unique (aimag_id, code),
  constraint sums_aimag_name_unique unique (aimag_id, name)
);

-- Supplier identity is separate from login identity. A clerk-created supplier
-- may have no auth.users row / profiles row (BR-12, data dictionary p. 122).
create table public.suppliers (
  id bigint generated by default as identity primary key,
  name varchar(150) not null,
  supplier_type text not null,
  phone varchar(20),
  sum_id bigint not null,
  approval_status text not null default 'PENDING',
  approved_by_id uuid,
  rejection_reason text,
  identity_type varchar(30),
  identity_code varchar(50),
  created_at timestamptz not null default now(),
  constraint suppliers_sum_fkey foreign key (sum_id)
    references public.sums (id) on update restrict on delete restrict,
  constraint suppliers_type_check check (
    supplier_type in ('HERDER', 'COOPERATIVE', 'BUSINESS')
  ),
  constraint suppliers_approval_status_check check (
    approval_status in ('PENDING', 'APPROVED', 'REJECTED')
  ),
  constraint suppliers_identity_pair_check check (
    (identity_type is null and identity_code is null)
    or (identity_type is not null and identity_code is not null)
  ),
  constraint suppliers_rejection_reason_check check (
    (approval_status = 'REJECTED'
      and rejection_reason is not null
      and length(btrim(rejection_reason)) > 0)
    or (approval_status in ('PENDING', 'APPROVED') and rejection_reason is null)
  )
);

create unique index suppliers_identity_unique_idx
  on public.suppliers (identity_type, identity_code)
  where identity_type is not null and identity_code is not null;

create index suppliers_sum_idx on public.suppliers (sum_id);
create index suppliers_approval_status_idx on public.suppliers (approval_status);

-- Supplier-specific fields from the final plan (provider type, name, phone,
-- aimag/sum) live in suppliers. profiles stores login identity, role, status,
-- and the supplier ownership link. Email and password stay in auth.users.
create table public.profiles (
  id uuid primary key,
  app_role text not null,
  status text not null default 'PENDING',
  supplier_id bigint,
  failed_login_attempts smallint not null default 0,
  locked_at timestamptz,
  locked_until timestamptz,
  created_at timestamptz not null default now(),
  constraint profiles_auth_user_fkey foreign key (id)
    references auth.users (id) on update restrict on delete restrict,
  constraint profiles_supplier_fkey foreign key (supplier_id)
    references public.suppliers (id) on update restrict on delete restrict,
  constraint profiles_supplier_unique unique (supplier_id),
  constraint profiles_app_role_check check (
    app_role in ('supplier', 'registration_clerk', 'quality_staff', 'management', 'admin')
  ),
  constraint profiles_status_check check (
    status in ('PENDING', 'ACTIVE', 'REJECTED', 'LOCKED')
  ),
  constraint profiles_failed_attempts_check check (
    failed_login_attempts between 0 and 5
  ),
  constraint profiles_supplier_role_check check (
    (app_role = 'supplier' and supplier_id is not null)
    or (app_role <> 'supplier' and supplier_id is null)
  ),
  constraint profiles_locked_until_check check (
    locked_until is null or locked_at is not null
  )
);

alter table public.suppliers
  add constraint suppliers_approved_by_fkey foreign key (approved_by_id)
  references public.profiles (id) on update restrict on delete restrict;

create index profiles_status_locked_idx on public.profiles (status, locked_at);

create table public.supply_info (
  id bigint generated by default as identity primary key,
  supplier_id bigint not null,
  weight_kg numeric(12, 3) not null,
  sum_id bigint not null,
  livestock_count integer not null default 0,
  declared_date date not null,
  created_at timestamptz not null default now(),
  constraint supply_info_supplier_fkey foreign key (supplier_id)
    references public.suppliers (id) on update restrict on delete restrict,
  constraint supply_info_sum_fkey foreign key (sum_id)
    references public.sums (id) on update restrict on delete restrict,
  constraint supply_info_weight_check check (
    weight_kg > 0
    and weight_kg <> 'NaN'::numeric
    and weight_kg <> 'Infinity'::numeric
  ),
  constraint supply_info_livestock_check check (livestock_count >= 0)
);

create index supply_info_supplier_date_idx
  on public.supply_info (supplier_id, declared_date);
create index supply_info_sum_date_idx
  on public.supply_info (sum_id, declared_date);

create table public.batch_counter (
  year integer primary key,
  sequence integer not null default 0,
  -- MN-YYYY-NNNNNN is a six-digit sequence. Reject the counter at the schema
  -- layer as well as inside create_batch() so an oversized value can never be
  -- truncated by lpad().
  constraint batch_counter_sequence_check check (sequence between 0 and 999999)
);

create table public.batch (
  id bigint generated by default as identity primary key,
  batch_code varchar(50) not null,
  supplier_id bigint not null,
  weight_kg numeric(12, 3) not null,
  received_date date not null,
  origin_sum_id bigint not null,
  status text not null default 'REGISTERED',
  registered_by_id uuid not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint batch_code_unique unique (batch_code),
  constraint batch_code_format_check check (
    batch_code ~ '^MN-[0-9]{4}-[0-9]{6}$'
  ),
  constraint batch_supplier_fkey foreign key (supplier_id)
    references public.suppliers (id) on update restrict on delete restrict,
  constraint batch_origin_sum_fkey foreign key (origin_sum_id)
    references public.sums (id) on update restrict on delete restrict,
  constraint batch_registered_by_fkey foreign key (registered_by_id)
    references public.profiles (id) on update restrict on delete restrict,
  constraint batch_weight_check check (
    weight_kg > 0
    and weight_kg <> 'NaN'::numeric
    and weight_kg <> 'Infinity'::numeric
  ),
  constraint batch_status_check check (status in ('REGISTERED', 'TESTED'))
);

create index batch_supplier_idx on public.batch (supplier_id);
create index batch_origin_sum_idx on public.batch (origin_sum_id);
create index batch_received_date_idx on public.batch (received_date);

create table public.quality_test (
  id bigint generated by default as identity primary key,
  batch_id bigint not null,
  fineness_micron numeric(6, 2),
  clean_yield_pct numeric(5, 2),
  admixture_pct numeric(5, 2),
  lab_result text,
  test_date date not null,
  created_by_id uuid not null,
  created_at timestamptz not null default now(),
  constraint quality_test_batch_fkey foreign key (batch_id)
    references public.batch (id) on update restrict on delete restrict,
  constraint quality_test_created_by_fkey foreign key (created_by_id)
    references public.profiles (id) on update restrict on delete restrict,
  constraint quality_test_fineness_check check (
    fineness_micron is null
    or (
      fineness_micron >= 0
      and fineness_micron <> 'NaN'::numeric
      and fineness_micron <> 'Infinity'::numeric
    )
  ),
  constraint quality_test_clean_yield_check check (
    clean_yield_pct is null or clean_yield_pct between 0 and 100
  ),
  constraint quality_test_admixture_check check (
    admixture_pct is null or admixture_pct between 0 and 100
  ),
  constraint quality_test_indicator_check check (
    fineness_micron is not null
    or clean_yield_pct is not null
    or admixture_pct is not null
    or (lab_result is not null and length(btrim(lab_result)) > 0)
  )
);

create index quality_test_batch_latest_idx
  on public.quality_test (batch_id, created_at desc, id desc);

create table public.qr_code (
  id bigint generated by default as identity primary key,
  batch_id bigint not null,
  token varchar(128) not null default gen_random_uuid()::text,
  url varchar(500) not null,
  storage_path text,
  status text not null default 'CREATED',
  created_at timestamptz not null default now(),
  ready_at timestamptz,
  constraint qr_code_batch_fkey foreign key (batch_id)
    references public.batch (id) on update restrict on delete restrict,
  constraint qr_code_batch_unique unique (batch_id),
  constraint qr_code_token_unique unique (token),
  constraint qr_code_status_check check (status in ('CREATED', 'READY')),
  constraint qr_code_ready_at_check check (
    (status = 'CREATED' and ready_at is null)
    or (status = 'READY' and ready_at is not null)
  )
);

-- Closed public catalog. Personal data and lab_result are deliberately absent.
-- animalCount is absent because V1 has no approved batch-to-supply allocation
-- relationship, so there is no valid value for it to publish.
create or replace function public.is_valid_publish_fields(p_fields jsonb)
returns boolean
language sql
immutable
set search_path = pg_catalog, pg_temp
as $$
  select case
    when p_fields is null or jsonb_typeof(p_fields) <> 'array' then false
    else not exists (
      select 1
      from jsonb_array_elements(p_fields) as element(field)
      where jsonb_typeof(field) <> 'string'
        or field #>> '{}' not in (
          'batchNo',
          'aimagName',
          'sumName',
          'quantityKg',
          'finenessMicron',
          'cleanYieldPct',
          'impurityPct',
          'testedAt',
          'verificationStatus'
        )
    )
  end;
$$;

create table public.publish_config (
  batch_id bigint primary key,
  published_fields jsonb not null default '[]'::jsonb,
  status text not null default 'PRIVATE',
  updated_at timestamptz not null default now(),
  updated_by_id uuid,
  constraint publish_config_batch_fkey foreign key (batch_id)
    references public.batch (id) on update restrict on delete restrict,
  constraint publish_config_updated_by_fkey foreign key (updated_by_id)
    references public.profiles (id) on update restrict on delete restrict,
  constraint publish_config_status_check check (status in ('PRIVATE', 'PUBLISHED')),
  constraint publish_config_fields_check check (
    public.is_valid_publish_fields(published_fields)
  )
);

create table public.audit_log (
  id bigint generated by default as identity primary key,
  occurred_at timestamptz not null default now(),
  action varchar(100) not null,
  entity varchar(100) not null,
  entity_id varchar(64),
  actor_id uuid,
  actor_role varchar(30),
  detail jsonb,
  ip_hash varchar(64),
  -- Audit history is append-only. A profile referenced by the audit trail
  -- must not be hard-deleted; RESTRICT forces soft deactivation instead of a
  -- SET NULL update that the audit UPDATE trigger would reject anyway.
  constraint audit_log_actor_fkey foreign key (actor_id)
    references public.profiles (id) on update restrict on delete restrict
);

create index audit_log_actor_time_idx on public.audit_log (actor_id, occurred_at);
create index audit_log_entity_idx on public.audit_log (entity, entity_id);
create index audit_log_action_time_idx on public.audit_log (action, occurred_at);

create table public.system_config (
  key varchar(100) primary key,
  value text not null,
  updated_by_id uuid,
  updated_at timestamptz not null default now(),
  constraint system_config_updated_by_fkey foreign key (updated_by_id)
    references public.profiles (id) on update restrict on delete restrict
);

